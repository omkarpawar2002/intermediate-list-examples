# List Methods :-

#1.append() :- This method is used to add single element to the end of list.
'''
li = [10,20,30,40]
print(li)
li.append(101)
print(li)
'''

#2.extend() :- This method is used to add multiple elements or any other iterable object to the end of list.
'''
li = [10,20,30,40]
print(li)
li.extend([102,2010])
print(li)
'''

#3.insert() :- This method is used to add single element at specified index position.
'''
li = [10,20,30,40]
print(li)
li.insert(2,101)
print(li)
'''

#4.remove() :- This method removes the specified element from list.
'''
li = [10,20,30,40]
print(li)
li.remove(10)
print(li)
'''

#5.pop() :- This method is used to remove and return last element in list.
'''
li = [10,20,30,40]
print(li)
li.pop()
print(li)
'''

#6.pop(index) :- This method is used to remove and return specified element from its index position.
'''
li = [10,20,30,40]
print(li)
li.pop(2)
print(li)
'''

#7.clear() :- This method is used to remove all elements inside list.
'''
li = [10,20,30,40]
print(li)
li.clear()
print(li)
'''

#8.index() :- This method returns the index position of specified element.
'''
li = [10,20,30,40]
print(li)
print(li.index(20))
'''

#9.count() :- This method returns the total count of occurrences of specified elements.
'''
li = [10,20,30,40]
print(li)
print(li.count(20))
'''

#10.copy() :- This method returns the shallow copy of list.
'''
li = [10,20,30,40]
print(li)
new = li.copy()
print(new)
'''

#11.reverse() :- This method is used to reverse the original list.
'''
li = [10,20,30,40]
print(li)
li.reverse()
print(li)
'''

#12.sort() :- This method is used to sort the list in ascending or descending order.
'''
li = [10,20,30,40]
print(li)
li.sort(reverse=True)
print(li)
'''




